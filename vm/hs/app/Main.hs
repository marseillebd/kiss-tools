-- gets either a byte address or a word address
lea :: OperandS -> Vm (Either Word32 Word32)
lea (OpdSImm w7) = pure . Right $ fromIntegral w7
lea (OpdSReg mode i) = case mode of
  Direct -> Right <$> readReg i
  Byte -> Left <$> do
    base <- readReg i
    pure $ base
  Stack -> Right <$> do
    sp <- readReg 0xD
    off <- readReg i
    pure (sp - off)
  Env -> Right <$> do
    ep <- readReg 0xE
    off <- readReg i
    pure (ep + off)
  Frame -> Right <$> do
    fp <- readReg 0xF
    off <- readReg i
    pure (fp + off)

condition :: Word32 -> Condition -> Word32 -> Bool
condition a f b =
  let flags = (if a == b then 1 else 0) .|.
              (if a < b then 2 else 0) .|.
              (if a > b then 4 else 0) .|.
              (if a > 0x7FFF_FFFF then 8 else 0)
   in flags .&. mask f /= 0
  where
  mask :: Condition -> Int
  mask UEq = 1
  mask ULt = 2
  mask ULe = 3
  mask UGt = 4
  mask UGe = 5
  mask UNe = 6
  mask ILtZ = 8

