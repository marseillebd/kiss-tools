effS src@(OpdSReg _ _) = lea src >>= \case
  Right wordAddr -> ldWord wordAddr
  Left byteAddr -> fromIntegral <$> ld8 byteAddr

effX :: OperandX -> Vm Word32
effX (OpdXImm w4) = pure $ fromIntegral w4
