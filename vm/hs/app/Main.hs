chunksOf :: Int -> [a] -> [[a]]
chunksOf _ [] = []
chunksOf n xs =
  let (group, rest) = splitAt n xs
   in group : chunksOf n rest

hexByte :: Word8 -> String
hexByte b
  | b < 0x10 = '0' : showHex b ""
  | otherwise = showHex b ""
